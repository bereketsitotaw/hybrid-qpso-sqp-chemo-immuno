%==========================================================================
% run_quadrotor_ocp.m  (EXPERIMENT ENTRY POINT)  -- FIXED DROP-IN
%==========================================================================

clear; clc; close all;

opts = struct( ...
    'seed', 1, ...
    'N', 40, ...
    'objective_mode', 'time_energy_L2', ...
    'T_guess', 6.0, ...
    'T_bounds', [0.5, 30.0], ...
    'C', 1.0, ...
    'wu', [1.0; 1.0], ...
    'a_max', 2.0, ...
    'max_velocity', 5.0, ...
    'safety_margin', 0.40, ...
    'num_obs', 8, ...
    'moving_obs', false, ...
    'constraint_upsample', 3, ...   % problem-side ineq upsample (optional)
    'enablePMP', true, ...
    'swarmSize', 120, ...
    'maxIter', 120, ...
    'nKnots', 10, ...
    'nStages', 3, ...
    ... % solver-side dense checker options (recommended)
    'dense_samples', 12, ...
    'dense_refine_factor', 2, ...
    'dense_refine_band', 0.25 ...
);

problem = define_quadrotor_nav_problem(opts);

fprintf('Calling solver...\n');
[solution, summary] = solveOCP(problem);

% Summary print
if isfield(problem,'generate_summary') && ~isempty(problem.generate_summary)
    problem.generate_summary(solution, summary, problem);
end

% Plotting/animation options
plotopts = struct( ...
    'show_reference', true, ...
    'show_arrows', true, ...
    'dense_check_sub', 12, ...   % plot-only dense check (Hermite)
    'animate', true, ...
    'frame_skip', 1, ...
    'fps', 30, ...
    'save_mp4', false, ...
    'mp4_name', 'quad_traj.mp4', ...
    'save_gif', false, ...
    'gif_name', 'quad_traj.gif', ...
    'plot_pmp', true ...
);

plot_quadrotor_results(solution, summary, problem, plotopts);
