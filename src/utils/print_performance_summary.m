function print_performance_summary(solution, summary)
%PRINT_PERFORMANCE_SUMMARY Console tables matching the original script output.

    p = solution.p;
    t = solution.time;
    x_opt = solution.x;
    y_opt = solution.y;
    z_opt = solution.z;
    u_opt = solution.u;
    v_opt = solution.v;
    T_opt = solution.T;
    J_opt = solution.J;

    [peak_y, idx_y] = max(y_opt);
    [peak_z, idx_z] = max(z_opt);
    tumor_reduction_pct = (p.x0 - x_opt(end)) / p.x0 * 100;

    BANG_OFF_THRESH = 0.01;

    u_phase_bang_on = (u_opt > 0.99 * p.umax);
    u_phase_singular = (u_opt >= BANG_OFF_THRESH & u_opt <= 0.99 * p.umax);
    u_phase_bang_off = (u_opt < BANG_OFF_THRESH);

    v_phase_bang_on = (v_opt > 0.99 * p.vmax);
    v_phase_singular = (v_opt >= BANG_OFF_THRESH & v_opt <= 0.99 * p.vmax);
    v_phase_bang_off = (v_opt < BANG_OFF_THRESH);

    fprintf('\n============================================================\n');
    fprintf('           OPTIMAL THERAPY PERFORMANCE SUMMARY\n');
    fprintf('           %s\n', summary.case_name);
    fprintf('============================================================\n\n');

    fprintf('--- Overall Results ---\n');
    disp(table(["Total Therapy Duration"; "Final Objective Cost"], [T_opt; J_opt], ...
        ["days"; "N/A"], 'VariableNames', {'Metric', 'Value', 'Units'}));

    fprintf('\n--- State Dynamics ---\n');
    disp(table( ...
        ["Tumor Reduction"; "Initial Tumor"; "Final Tumor"; ...
         "Peak Immune Response (y)"; "Time of Peak (y)"; ...
         "Peak Antigen Level (z)"; "Time of Peak (z)"], ...
        [tumor_reduction_pct; p.x0; x_opt(end); peak_y; t(idx_y); peak_z; t(idx_z)], ...
        ["%"; "population"; "population"; "density"; "days"; "concentration"; "days"], ...
        'VariableNames', {'Metric', 'Value', 'Units'}));

    fprintf('\n--- Control Strategy: Chemotherapy (u) ---\n');
    disp(table( ...
        ["Bang-On Duration"; "Interior/Singular Duration"; "Bang-Off Duration"; "Dosing Intensity (Avg)"], ...
        [trapz(t, u_phase_bang_on); trapz(t, u_phase_singular); trapz(t, u_phase_bang_off); ...
         trapz(t, u_opt) / T_opt * 100], ...
        ["days"; "days"; "days"; "%"], ...
        'VariableNames', {'Metric', 'Value', 'Units'}));

    fprintf('\n--- Control Strategy: Immunotherapy (v) ---\n');
    disp(table( ...
        ["Bang-On Duration"; "Interior/Singular Duration"; "Bang-Off Duration"; "Dosing Intensity (Avg)"], ...
        [trapz(t, v_phase_bang_on); trapz(t, v_phase_singular); trapz(t, v_phase_bang_off); ...
         trapz(t, v_opt) / T_opt * 100], ...
        ["days"; "days"; "days"; "%"], ...
        'VariableNames', {'Metric', 'Value', 'Units'}));

    fprintf('\n--- Computational Efficiency ---\n');
    disp(table( ...
        ["QPSO Global Search"; "fmincon Local Refinement"; "Total Computation Time"], ...
        [summary.qpso_time; summary.fmincon_time; summary.total_time], ...
        ["seconds"; "seconds"; "seconds"], ...
        'VariableNames', {'Metric', 'Value', 'Units'}));
end
